#!/usr/bin/env node
// Compile every published book route from editable layout sources. No browser-time rendering.
import { readFileSync, readdirSync, mkdirSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, relative, resolve, posix } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const project = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const layoutDir = join(project, 'layout');
export const notesDir = join(project, 'notes');
export const mainClasses = Object.freeze({
  overview: 'p2n-page p2n-book-index',
  chapter: 'p2n-page-frame p2n-page-frame--chapter',
  map: 'p2n-page-frame p2n-page-frame--chapter-map',
  section: 'p2n-page-frame p2n-page-frame--section',
  summary: 'p2n-page-frame p2n-page-frame--summary',
});
// Shared markup lives in layout/components/. Page slots stay in layout/pages/.
export const componentNames = Object.freeze(['head', 'brand', 'navigation', 'header', 'main', 'footer']);
export const generatedNotice = '<!-- Generated by scripts/build-books.mjs. Edit layout/book.html, layout/components/, or layout/pages/, not this output. -->';
const slotNames = ['head', 'content', 'scripts', 'trailing'];
const generatedMark = 'Generated by scripts/build-books.mjs';
export const sourceMarker = name => `<!-- source: ${name}. Edit this file. The compiler does not generate this file. -->\n`;
// Ignore only whitespace on empty lines and at slot boundaries, not text or code.
export const normalizeSlot = s => s.replace(/^[ \t]+$/gm, '').trim();
const escape = s => String(s).replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]);
export function files(root, suffix = '.html') {
  if (!existsSync(root)) return [];
  return readdirSync(root, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name)).flatMap(e =>
    e.isDirectory() && !e.name.startsWith('_') ? files(join(root, e.name), suffix) :
      e.isFile() && e.name.endsWith(suffix) ? [join(root, e.name)] : []);
}
export function publishedRoutes(root = notesDir) {
  return readdirSync(root).filter(n => /^book[1-9]\d*$/.test(n)).flatMap(n => files(join(root, n)))
    .map(p => relative(root, p).split('\\').join('/')).sort();
}
// Chapter maps share the existing core-book card structure. Reject bespoke
// presentation at the source boundary rather than hiding it in generated HTML.
export function validateChapterPresentation(page) {
  if (/\b(?:Practice coverage|Exam practice|DSE coverage)<\/h2>/i.test(page.content)) {
    throw new Error(`${page.route}: remove the practice status block; use real shared MC/LQ quizzes`);
  }
  if (page.type !== 'map') return;
  const intro = '<p class="kicker">[^<]+<\\/p>\\s*<h1>[^<]+<\\/h1>(?:\\s*<p class="lede">[^<]+<\\/p>)?';
  const card = '<a href="[^" ]+\\.html">\\s*<span class="num">[^<]+<\\/span>\\s*<strong>[^<]+<\\/strong>(?:\\s*<span>[^<]+<\\/span>)?\\s*<\\/a>';
  const map = new RegExp(`^\\s*${intro}\\s*<div class="toc"(?: id="chapter-sections")?>\\s*(?:${card}\\s*)+<\\/div>([\\s\\S]*)$`);
  const match = map.exec(page.content);
  if (!match) throw new Error(`${page.route}: chapter maps require the shared title, introduction and toc cards`);
  // Core maps already have optional PDF links, notes and book navigation.
  // New maps need no extra block when no verified chapter PDF exists.
  const tail = match[1].trim();
  if (tail && !/^(?:<p(?: class="(?:note|pager)")?>[\s\S]*?<\/p>\s*)+$/.test(tail)) {
    throw new Error(`${page.route}: chapter maps cannot add bespoke sections`);
  }
  if (!/href="summary\.html"/.test(page.content)) {
    throw new Error(`${page.route}: chapter maps require a Summary card or link`);
  }
}
export function loadPages(root = layoutDir) {
  return files(join(root, 'pages')).map(file => {
    const raw = readFileSync(file, 'utf8');
    if (raw.includes(generatedMark)) throw new Error(`${file}: page source must not carry the generated-file notice`);
    const match = /^<!-- page\n([\s\S]*?)\n-->\n/.exec(raw);
    if (!match) throw new Error(`${file}: missing page metadata`);
    const meta = JSON.parse(match[1]);
    const route = relative(join(root, 'pages'), file).split('\\').join('/');
    if (!/^book[1-9]\d*\/(?:ch[\w-]+\/)?[\w-]+\.html$/.test(route)) throw new Error(`Invalid route: ${route}`);
    if (!meta || typeof meta !== 'object' || Array.isArray(meta) || !Object.hasOwn(mainClasses, meta.type) || typeof meta.title !== 'string') {
      throw new Error(`${route}: invalid title or page type`);
    }
    if (Object.keys(meta).some(k => !['type', 'title'].includes(k))) throw new Error(`${route}: unknown page metadata`);
    const pieces = raw.slice(match[0].length).split(/<!-- slot:(\w+) -->\n/);
    if (pieces[0] || pieces.length !== 9) throw new Error(`${route}: expected four explicit slots`);
    const slots = {};
    slotNames.forEach((name, i) => {
      if (pieces[i * 2 + 1] !== name) throw new Error(`${route}: expected ${name} slot`);
      slots[name] = pieces[i * 2 + 2];
    });
    if (/<(?:html|head|body|main)\b|<[^>]*\bp2n-(?:top|context-nav)\b[^>]*>|deploy-commit-footer/i.test(Object.values(slots).join(''))) {
      throw new Error(`${route}: page slots must not contain layout markup`);
    }
    const page = { route, ...meta, ...slots };
    validateChapterPresentation(page);
    return page;
  });
}
function readEditableSource(file, name, { dropFinalNewline }) {
  const raw = readFileSync(file, 'utf8');
  if (raw.includes(generatedMark)) throw new Error(`${file}: editable source must not carry the generated-file notice`);
  const marker = sourceMarker(name);
  if (!raw.startsWith(marker)) throw new Error(`${file}: editable source must identify itself as ${name}`);
  if (!raw.endsWith('\n')) throw new Error(`${file}: editable source must end with a newline`);
  const body = raw.slice(marker.length);
  return dropFinalNewline ? body.slice(0, -1) : body;
}
// Resolve {{component:name}} left to right, then depth first. Do not scan lesson text.
export function composeTemplate(arrangement, components) {
  const expanding = [];
  const expand = name => {
    if (expanding.includes(name)) throw new Error(`Component cycle: ${expanding.concat(name).join(' -> ')}`);
    if (!Object.hasOwn(components, name)) throw new Error(`Unknown component: ${name}`);
    expanding.push(name);
    const body = components[name].replace(/\{\{component:([a-z]+)\}\}/g, (_, child) => expand(child));
    expanding.pop();
    return body;
  };
  const composed = arrangement.replace(/\{\{component:([a-z]+)\}\}/g, (_, name) => expand(name));
  if (/\{\{component:/.test(composed)) throw new Error('Unresolved component placeholder');
  const doctype = '<!DOCTYPE html>\n';
  if (!composed.startsWith(doctype)) throw new Error('Book arrangement must start with <!DOCTYPE html>');
  return `${doctype}${generatedNotice}\n${composed.slice(doctype.length)}`;
}
export function loadLayout(root = layoutDir) {
  const dir = join(root, 'components');
  if (!existsSync(dir)) throw new Error(`${root}: missing components directory`);
  const found = readdirSync(dir).sort();
  const expected = componentNames.map(name => `${name}.html`).sort();
  if (found.join('\n') !== expected.join('\n')) throw new Error(`${dir}: expected exactly ${expected.join(', ')}`);
  const components = Object.fromEntries(componentNames.map(name => [name, readEditableSource(join(dir, `${name}.html`), name, { dropFinalNewline: true })]));
  const arrangement = readEditableSource(join(root, 'book.html'), 'book', { dropFinalNewline: false });
  const template = composeTemplate(arrangement, components);
  const books = JSON.parse(readFileSync(join(root, 'books.json'), 'utf8'));
  if (!books || typeof books !== 'object' || Array.isArray(books)) throw new Error('Expected book identities');
  for (const [id, book] of Object.entries(books)) {
    if (!/^book[1-9]\d*$/.test(id) || !book || typeof book.label !== 'string' || typeof book.icon !== 'string' ||
        Object.keys(book).some(key => !['label', 'icon'].includes(key))) throw new Error(`Invalid book identity: ${id}`);
  }
  return { template, books, components, arrangement };
}
export const defaultFooter = Object.freeze({ commit: 'local', subject: '' });
export function renderPage(page, { template, books }, footer = defaultFooter) {
  const book = page.route.split('/')[0];
  const config = books[book];
  if (!config) throw new Error(`${page.route}: unknown book`);
  const root = '../'.repeat(page.route.split('/').length - 1);
  const home = posix.relative(posix.dirname(page.route), `${book}/index.html`);
  const trail = [{ label: 'All books', href: `${root}index.html` }, { label: `Book ${book.slice(4)}`, href: `${root}${book}/index.html` }];
  const chapter = page.route.split('/')[1].match(/^ch(\d+)-/);
  if (chapter) trail.push({ label: `Ch.${Number(chapter[1])}`, href: 'index.html' });
  if (page.type === 'section') {
    const number = posix.basename(page.route, '.html').match(/^(\d+)-(\d+)$/);
    if (!number) throw new Error(`${page.route}: section needs a numeric label`);
    trail.push({ label: `${number[1]}.${number[2]}` });
  } else if (page.type === 'summary') trail.push({ label: 'Summary' });
  const link = item => `<a href="${item.href}">${escape(item.label)}</a>`;
  const middle = trail.slice(1, -1);
  const breadcrumb = trail.map((item, i) => `<li${i > 0 && i < trail.length - 1 ? ' class="p2n-crumb-middle"' : ''}>${i === trail.length - 1 ? `<strong aria-current="page">${escape(item.label)}</strong>` : link(item)}</li>`);
  if (middle.length) breadcrumb.splice(1, 0, `<li class="p2n-crumb-collapsed"><details class="p2n-nav-menu"><summary aria-label="Show parent pages">…</summary><div class="p2n-nav-popup">${middle.map(link).join('')}</div></details></li>`);
  const navigation = `<ol class="p2n-breadcrumb" aria-label="Breadcrumb">${breadcrumb.join('')}</ol><details class="p2n-nav-menu p2n-books-menu"><summary>Books</summary><div class="p2n-nav-popup">${Object.entries(books).map(([id, b]) => link({ href: `${root}${id}/index.html`, label: b.label })).join('')}<a href="${root}qb/index.html">Question bank</a></div></details><a class="p2n-qb-link" href="${root}qb/index.html">Question bank</a>`;
  // Component placeholders are already resolved. Replace only these values.
  // Lesson text is a replacement value, so braces inside a lesson stay literal.
  const slots = Object.fromEntries(slotNames.map(name => [name, normalizeSlot(page[name])]));
  const values = { ...slots, title: escape(page.title), root, home, book, label: escape(config.label), icon: escape(config.icon), navigation, mainClass: mainClasses[page.type], deployCommit: escape(footer.commit), deploySubject: footer.subject ? ` <span class="deploy-commit-subject">${footer.subject}</span>` : '' };
  return template.replace(/\{\{(\w+)\}\}/g, (_, key) => {
    if (!Object.hasOwn(values, key)) throw new Error(`Unknown layout slot: ${key}`);
    return values[key];
  }).trimEnd() + '\n';
}
// Deployment owns this footer, not lesson sources. Preserve it when rebuilding.
export function footerFrom(html) {
  const footer = html.match(/<footer\b[^>]*class="deploy-commit-footer"[^>]*>[\s\S]*?<\/footer>/)?.[0];
  if (!footer) return defaultFooter;
  return { commit: footer.match(/data-commit="([^"]*)"/)?.[1] ?? 'local', subject: footer.match(/<span class="deploy-commit-subject">([^<]*)<\/span>/)?.[1] ?? '' };
}
export function checkBooks({ output = notesDir, source = layoutDir, write = false } = {}) {
  const pages = loadPages(source), layout = loadLayout(source), errors = [];
  const expected = new Set(pages.map(p => p.route));
  for (const route of publishedRoutes(output)) if (!expected.has(route)) errors.push(`${route}: published route has no layout source`);
  for (const page of pages) {
    const dest = join(output, page.route);
    const current = existsSync(dest) ? readFileSync(dest, 'utf8') : '';
    const rendered = renderPage(page, layout, footerFrom(current));
    if (current !== rendered) {
      if (write) { mkdirSync(dirname(dest), { recursive: true }); writeFileSync(dest, rendered); }
      else errors.push(`${page.route}: stale generated page; run node paper2notes/scripts/build-books.mjs`);
    }
  }
  return { count: pages.length, errors };
}
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  if (process.argv.slice(2).some(a => a !== '--check')) throw new Error('Usage: build-books.mjs [--check]');
  const result = checkBooks({ write: !process.argv.includes('--check') });
  if (result.errors.length) { console.error(result.errors.join('\n')); process.exitCode = 1; }
  else console.log(`Shared book layout: ${result.count} routes ${process.argv.includes('--check') ? 'checked' : 'built'}.`);
}
